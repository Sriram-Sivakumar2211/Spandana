import os
import sys
import json
import argparse
import numpy as np
import torch
from torch.utils.data import DataLoader

sys.path.insert(0, os.path.abspath("."))

from lnn.model import SpandanaLTC
from utils.common import get_device
from utils.torch_dataset import build_sequences, BearingSequenceDataset
from preprocessing.bearing_common import BEARING_CLASSES
from evaluation.metrics import (
    classification_metrics, pr_curve_per_class, model_size_bytes,
    count_parameters, measure_inference_latency, predict_all,
)

"""
Phase 7 evaluation for the LTC (ncps) model -- Spandana's only model. There
is no LSTM to benchmark against anymore (removed per project mandate), so
this reports the LTC's own metrics standalone rather than as a comparison
table. Numbers are never adjusted or omitted to make the model look better;
if a metric is weak, it is reported as-is.
"""


def load_test_sequences(unified_path: str, seq_len: int, stride: int):
    data = np.load(unified_path, allow_pickle=True)
    X, y, groups = data["X_test"], data["y_test"], data["group_test"]
    return build_sequences(X, y, groups, seq_len=seq_len, stride=stride)


def evaluate_model(model: torch.nn.Module, checkpoint_path: str, train_result_path: str,
                    test_loader, device: torch.device, num_classes: int) -> dict:
    checkpoint = torch.load(checkpoint_path, map_location=device, weights_only=False)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.to(device)

    y_true, y_pred, y_proba = predict_all(model, test_loader, device)
    metrics = classification_metrics(y_true, y_pred, y_proba, num_classes)
    pr_curves = pr_curve_per_class(y_true, y_proba, num_classes)

    sample_input = next(iter(test_loader))[0][:1]
    latency = measure_inference_latency(model, sample_input, device)

    train_result = {}
    if os.path.exists(train_result_path):
        with open(train_result_path, "r", encoding="utf-8") as f:
            train_result = json.load(f)

    return {
        "name": "ltc",
        "metrics": metrics,
        "pr_curves": pr_curves,
        "latency_ms": latency,
        "model_size_bytes": model_size_bytes(checkpoint_path),
        "n_parameters": count_parameters(model),
        "training_time_sec": train_result.get("training_time_sec"),
        "epochs_run": train_result.get("epochs_run"),
        "best_epoch": train_result.get("best_epoch"),
    }


def render_markdown(res: dict) -> str:
    m = res["metrics"]
    lines = ["# LTC Model Evaluation Report (Phase 7)", ""]
    lines.append("Auto-generated by `evaluation/evaluate_model.py`. Spandana's only model is the "
                  "Liquid Time-Constant Network (`ncps.torch.LTC`, wired via `AutoNCP`) -- there is "
                  "no LSTM baseline in this project; these are the model's standalone metrics.")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    lines.append(f"| Accuracy | {m['accuracy']:.4f} |")
    lines.append(f"| Precision (macro) | {m['precision_macro']:.4f} |")
    lines.append(f"| Recall (macro) | {m['recall_macro']:.4f} |")
    lines.append(f"| F1 (macro) | {m['f1_macro']:.4f} |")
    lines.append(f"| ROC AUC (macro) | {m['roc_auc_macro']:.4f} |")
    lines.append(f"| False Positives (total) | {m['false_positives_total']} |")
    lines.append(f"| False Negatives (total) | {m['false_negatives_total']} |")
    lines.append(f"| Mean Inference Latency (ms) | {res['latency_ms']['mean_ms']:.4f} |")
    lines.append(f"| P95 Inference Latency (ms) | {res['latency_ms']['p95_ms']:.4f} |")
    lines.append(f"| Model Size (bytes) | {res['model_size_bytes']} |")
    lines.append(f"| Parameter Count | {res['n_parameters']} |")
    lines.append(f"| Training Time (sec) | {res['training_time_sec']} |")
    lines.append(f"| Epochs Run | {res['epochs_run']} |")
    lines.append("")
    lines.append("## Confusion Matrix")
    lines.append(f"Classes (index order): {BEARING_CLASSES}")
    lines.append("```")
    for row_vals in m["confusion_matrix"]:
        lines.append(str(row_vals))
    lines.append("```")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default=os.path.join("data", "unified", "unified_bearing_dataset.npz"))
    parser.add_argument("--config", default=os.path.join("configs", "lnn_config.json"))
    parser.add_argument("--checkpoint", default=os.path.join("data", "checkpoints", "lnn", "best_ltc.pt"))
    parser.add_argument("--reports-dir", default="reports")
    args = parser.parse_args()

    with open(args.config, "r", encoding="utf-8") as f:
        cfg = json.load(f)

    device = get_device()
    num_classes = len(BEARING_CLASSES)
    feature_dim = 17

    seq_X, seq_y = load_test_sequences(args.data, cfg["seq_len"], cfg["stride"])
    loader = DataLoader(BearingSequenceDataset(seq_X, seq_y), batch_size=cfg["batch_size"], shuffle=False)

    model = SpandanaLTC(
        input_size=feature_dim, num_classes=num_classes, hidden_size=cfg["hidden_size"],
        sparsity_level=cfg["sparsity_level"], ode_unfolds=cfg["ode_unfolds"], seed=cfg["seed"],
    )

    result = evaluate_model(
        model, args.checkpoint, os.path.join(os.path.dirname(args.checkpoint), "train_result.json"),
        loader, device, num_classes,
    )

    os.makedirs(args.reports_dir, exist_ok=True)
    with open(os.path.join(args.reports_dir, "model_evaluation.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, default=str)

    md = render_markdown(result)
    with open(os.path.join(args.reports_dir, "model_evaluation_report.md"), "w", encoding="utf-8") as f:
        f.write(md)

    print(md)


if __name__ == "__main__":
    main()
